
import cv2
import numpy as np
import pandas as pd
import random

from pathlib import Path


# =====================================================
# 1. CONFIGURATION
# =====================================================

ROOT = Path(__file__).resolve().parent.parent

IMAGE_DIR = ROOT / "dataset" / "train" / "egg"

SAM_MASK_DIR = (
    ROOT / "outputs" / "sam_masks" /
    "train" / "binary_masks"
)

SAM_COMBINED_DIR = ROOT / "outputs" / "sam_masks" / "train"

OUTPUT_DIR = ROOT / "outputs" / "grabcut_validation"

OVERLAY_DIR = OUTPUT_DIR / "overlays"

MASK_DIR = OUTPUT_DIR / "masks"

SAMPLE_SIZE = 10
RANDOM_SEED = 42
ITERATIONS = 5

for directory in [OUTPUT_DIR, OVERLAY_DIR, MASK_DIR]:

    if directory.exists() and not directory.is_dir():
        raise NotADirectoryError(
            f"{directory} exists as a file."
        )

    directory.mkdir(parents=True, exist_ok=True)


# =====================================================
# 2. E2: LAB + RECTANGLE GRABCUT
# =====================================================

def segment_grabcut(image):

    height, width = image.shape[:2]

    # Convert image to LAB
    lab = cv2.cvtColor(
        image,
        cv2.COLOR_BGR2LAB
    )

    # Reduce noise
    lab = cv2.GaussianBlur(
        lab,
        (5, 5),
        0
    )

    # Initialize GrabCut mask
    mask = np.zeros(
        (height, width),
        dtype=np.uint8
    )

    bgd_model = np.zeros(
        (1, 65),
        dtype=np.float64
    )

    fgd_model = np.zeros(
        (1, 65),
        dtype=np.float64
    )

    # Rectangle initialization
    margin_x = int(width * 0.05)
    margin_y = int(height * 0.05)

    rect = (
        margin_x,
        margin_y,
        width - 2 * margin_x,
        height - 2 * margin_y
    )

    # Run GrabCut
    cv2.grabCut(
        lab,
        mask,
        rect,
        bgd_model,
        fgd_model,
        ITERATIONS,
        cv2.GC_INIT_WITH_RECT
    )

    # Extract foreground
    foreground = np.where(
        (mask == cv2.GC_FGD) |
        (mask == cv2.GC_PR_FGD),
        255,
        0
    ).astype(np.uint8)

    # Morphological refinement
    kernel = cv2.getStructuringElement(
        cv2.MORPH_ELLIPSE,
        (5, 5)
    )

    foreground = cv2.morphologyEx(
        foreground,
        cv2.MORPH_OPEN,
        kernel
    )

    foreground = cv2.morphologyEx(
        foreground,
        cv2.MORPH_CLOSE,
        kernel,
        iterations=2
    )

    # Find external contours
    contours, _ = cv2.findContours(
        foreground,
        cv2.RETR_EXTERNAL,
        cv2.CHAIN_APPROX_SIMPLE
    )

    final_mask = np.zeros(
        (height, width),
        dtype=np.uint8
    )

    valid_contours = [
        c for c in contours
        if cv2.contourArea(c) >= 500
    ]

    if valid_contours:

        largest = max(
            valid_contours,
            key=cv2.contourArea
        )

        cv2.drawContours(
            final_mask,
            [largest],
            -1,
            255,
            cv2.FILLED
        )

    return final_mask


# =====================================================
# 3. LOAD SAM REFERENCE MASK
# =====================================================

def load_sam_mask(image_path):

    # Combined mask generated by SAM pipeline
    mask_path = (
        SAM_COMBINED_DIR /
        f"{image_path.stem}_combined.png"
    )

    if not mask_path.is_file():
        return None

    mask = cv2.imread(
        str(mask_path),
        cv2.IMREAD_GRAYSCALE
    )

    if mask is None:
        return None

    return np.where(
        mask > 127,
        255,
        0
    ).astype(np.uint8)


# =====================================================
# 4. EVALUATION METRICS
# =====================================================

def calculate_metrics(prediction, reference):

    pred = prediction > 127
    ref = reference > 127

    intersection = np.logical_and(
        pred,
        ref
    ).sum()

    union = np.logical_or(
        pred,
        ref
    ).sum()

    tp = intersection

    fp = np.logical_and(
        pred,
        ~ref
    ).sum()

    fn = np.logical_and(
        ~pred,
        ref
    ).sum()

    iou = (
        tp / union
        if union > 0 else 0
    )

    dice = (
        2 * tp / (2 * tp + fp + fn)
        if (2 * tp + fp + fn) > 0 else 0
    )

    precision = (
        tp / (tp + fp)
        if (tp + fp) > 0 else 0
    )

    recall = (
        tp / (tp + fn)
        if (tp + fn) > 0 else 0
    )

    f1 = (
        2 * precision * recall / (precision + recall)
        if (precision + recall) > 0 else 0
    )

    return {
        "IoU": round(float(iou), 4),
        "Dice": round(float(dice), 4),
        "Precision": round(float(precision), 4),
        "Recall": round(float(recall), 4),
        "F1": round(float(f1), 4)
    }


# =====================================================
# 5. CREATE OVERLAY
# =====================================================

def create_overlay(image, mask):

    overlay = image.copy()

    green = np.zeros_like(image)
    green[:] = (0, 255, 0)

    segmented = cv2.bitwise_and(
        green,
        green,
        mask=mask
    )

    overlay = cv2.addWeighted(
        image,
        0.65,
        segmented,
        0.35,
        0
    )

    contours, _ = cv2.findContours(
        mask,
        cv2.RETR_EXTERNAL,
        cv2.CHAIN_APPROX_SIMPLE
    )

    cv2.drawContours(
        overlay,
        contours,
        -1,
        (0, 0, 255),
        2
    )

    return overlay


# =====================================================
# 6. SELECT REPRESENTATIVE IMAGES
# =====================================================

def select_images():

    images = []

    for extension in ["*.jpg", "*.jpeg", "*.png"]:
        images.extend(
            IMAGE_DIR.glob(extension)
        )

    images = sorted(images)

    if len(images) < SAMPLE_SIZE:
        raise ValueError(
            f"Need {SAMPLE_SIZE} images, "
            f"but found {len(images)}."
        )

    # Reproducible random sample
    rng = random.Random(RANDOM_SEED)

    return rng.sample(
        images,
        SAMPLE_SIZE
    )


# =====================================================
# 7. MAIN VALIDATION
# =====================================================

def main():

    selected_images = select_images()

    results = []

    print("\n========== GRABCUT VALIDATION ==========")

    print("Images selected:", len(selected_images))

    for index, image_path in enumerate(
        selected_images,
        start=1
    ):

        print(
            f"\nProcessing {index}/{SAMPLE_SIZE}: "
            f"{image_path.name}"
        )

        image = cv2.imread(
            str(image_path)
        )

        if image is None:
            print("Unable to read image. Skipping.")
            continue

        # Generate GrabCut mask
        prediction = segment_grabcut(image)

        # Save predicted mask
        cv2.imwrite(
            str(MASK_DIR / f"{image_path.stem}.png"),
            prediction
        )

        # Save overlay
        overlay = create_overlay(
            image,
            prediction
        )

        cv2.imwrite(
            str(OVERLAY_DIR / f"{image_path.stem}.jpg"),
            overlay
        )

        # Load corresponding SAM reference
        reference = load_sam_mask(image_path)

        row = {
            "image": image_path.name,
            "GrabCut_area_percent": round(
                np.count_nonzero(prediction) /
                prediction.size * 100,
                2
            )
        }

        if reference is not None:

            if reference.shape != prediction.shape:

                reference = cv2.resize(
                    reference,
                    (prediction.shape[1], prediction.shape[0]),
                    interpolation=cv2.INTER_NEAREST
                )

            metrics = calculate_metrics(
                prediction,
                reference
            )

            row.update(metrics)

            print(
                "IoU:", metrics["IoU"],
                "| Dice:", metrics["Dice"],
                "| F1:", metrics["F1"]
            )

        else:

            row["IoU"] = np.nan
            row["Dice"] = np.nan
            row["Precision"] = np.nan
            row["Recall"] = np.nan
            row["F1"] = np.nan

            print(
                "SAM reference mask missing. "
                "Visual inspection only."
            )

        results.append(row)

    # =================================================
    # 8. SAVE REPORT
    # =================================================

    df = pd.DataFrame(results)

    csv_path = OUTPUT_DIR / "grabcut_evaluation.csv"

    df.to_csv(
        csv_path,
        index=False
    )

    metric_columns = [
        "IoU",
        "Dice",
        "Precision",
        "Recall",
        "F1"
    ]

    available = df[metric_columns].dropna()

    print("\n========== EVALUATION SUMMARY ==========")

    if not available.empty:

        print(
            available.mean().round(4)
        )

    else:

        print(
            "No matching SAM reference masks found."
        )

    print("\nImages evaluated:", len(df))

    print("Report saved:", csv_path)

    print("\nValidation completed!")


# =====================================================
# 9. ENTRY POINT
# =====================================================

if __name__ == "__main__":

    main()
